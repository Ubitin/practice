// ============================================================
//  01_cf1486d_fixed.cpp —— CF 1486D Max Median（正确解法）
//
//  原文件 test_/01.cpp 保持原样、未做任何改动。
//
//  题意：n 个数、整数 k，求【长度至少为 k 的子段】的最大中位数。
//        中位数定义：长度为 m 的数组，中位数 = 升序后第 ⌈m/2⌉ 小的元素
//        （偶数长度取下中位数；下面 §注释 里给了另一种定义的改法）
//
//  ── 原码错在哪 ──
//    原码把 n 个数全塞进大根堆，然后弹出 t = ⌊k/2⌋+1 次，输出最后弹出的那个。
//    这算的是【整个数组的第 t 大】，与"某个连续子段的中位数"完全无关——
//    它彻底忽略了"子段必须连续、长度至少 k"这个约束。
//    实测反例：n=5, k=3, a={5,1,1,1,5} → 原码输出 5，正确答案是 1。
//    （官方样例 n=5,k=3,a={1,2,3,4,5} → 原码凑巧输出 4 = 正确答案，所以看不出问题）
//
//  ── 正解思路：二分答案 + 转 ±1 + 前缀最小值 ──
//    二分答案 x（答案在 [1, max(a)] 内）。判定"是否存在中位数 ≥ x 的子段"：
//      · a[i] ≥ x 记 +1，否则记 -1，得到数组 b
//      · 关键等价：长为 m 的子段中位数 ≥ x
//          ⟺ 该段中 ≥ x 的元素个数 ≥ m - ⌈m/2⌉ + 1     （中位数定义展开）
//          ⟺ (#≥x) - (#<x) > 0
//          ⟺ b 在该段的元素和 > 0
//        逐档核对（m=2 需 2 个 ≥x；m=3 需 2 个；m=4 需 3 个；m=5 需 3 个）
//      · 于是只需判断：是否存在 i < j 使 j - i ≥ k 且 pre[j] - pre[i] > 0
//          ⟺ pre[j] > min(pre[i])，其中 i 取遍 0..j-k
//      · 用一个变量滚动维护 min(pre[0..j-k]) 即可，整体 O(n)
//    二分 O(log n) × 判定 O(n) = O(n log n)
//
//  ⚠️ 最常见的错法：把 min 取成 pre[0..j-1]（少了 -k），
//     那就允许了长度 < k 的子段 → 答案偏大 → WA
// ============================================================
#include <bits/stdc++.h>
using namespace std;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int n, k;
    cin >> n >> k;
    vector<int> a(n);
    int mx = 0;
    for (int i = 0; i < n; ++i) {
        cin >> a[i];
        mx = max(mx, a[i]);
    }

    vector<int> pre(n + 1);
    auto check = [&](int x) -> bool {
        pre[0] = 0;
        for (int i = 0; i < n; ++i)
            pre[i + 1] = pre[i] + (a[i] >= x ? 1 : -1);

        // 需要存在 i < j 且 j-i >= k 使 pre[j] - pre[i] > 0
        // ⟺ pre[j] > min(pre[0 .. j-k])
        int mn = INT_MAX;
        for (int j = k; j <= n; ++j) {
            mn = min(mn, pre[j - k]);     // ★ 只把下标 ≤ j-k 的纳入候选
            if (pre[j] > mn) return true; // 严格大于：对应【下中位数】⌈m/2⌉
        }
        return false;
    };

    int lo = 1, hi = mx;                  // 答案 ≥ 1（k≥1 时单元素子段必可行）
    while (lo < hi) {
        int mid = lo + (hi - lo + 1) / 2; // 上取整：求最大可行值
        if (check(mid)) lo = mid;
        else            hi = mid - 1;
    }
    cout << lo << '\n';
    return 0;
}

// ------------------------------------------------------------
// 两种中位数定义与判定条件的对应（很容易搞反，务必看题面原句）：
//   · 下中位数 第 ⌈m/2⌉ 小（偶数长度取偏小的那个）→ 子段和 > 0  → 上面这版
//   · 上中位数 第 ⌈(m+1)/2⌉ 小（偶数长度取偏大的那个）→ 子段和 ≥ 0
//   只改一处： if (pre[j] > mn)  →  if (pre[j] >= mn)
//   ⚠️ CF1486D 官方样例 n=5,k=3,a={1,2,3,4,5} 在两种定义下答案都是 4，
//      所以光靠样例区分不出用的是哪一种 —— 这也是这道题最容易踩的暗坑。
