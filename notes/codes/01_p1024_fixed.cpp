// ============================================================
//  01_p1024_fixed.cpp —— P1024 一元三次方程求解（修正版）
//
//  原文件 test_/01.cpp 保持原样、未做任何改动。
//
//  题意：ax^3+bx^2+cx+d=0 在 [-100,100] 内恰有三个不同实根，两两间距 >= 1，
//        从小到大输出，精确到小数点后 2 位。
//
//  ── 原码漏根的【唯一主因】：二分算出根，却没有输出 ──
//      else if(f(l) * f(r) < 0){
//          while(abs(l - r) > eps){ ...二分... }
//          // ←←← 这里缺了一句 printf！算完就丢了
//      }
//    于是程序【只会输出整数根】（那些被 fabs(f(l)) < eps 分支抓到的）。
//    实测：题面样例 1 -5 -4 20（根 -2/2/5 全是整数）能过；
//          1 0 -2 0（根 -1.41/0/1.41）只输出 0.00；
//          随机 1000 组三实根方程，漏根 1000/1000 组（100%）。
//          只在二分分支后补一句 printf，就降到 0/1000 组。
//
//  ── 另外两处隐患 ──
//    ① fabs(f(l)) < 1e-4 判的是【函数值】不是【到根的距离】：
//       系数整体缩小 1e-8 时，一堆整数点的函数值都 < 1e-4 → 假根刷屏
//       （实测 a=1e-8,b=0,c=-2e-8,d=0 输出了 43 个"根"）
//       本项目用 f(l) == 0.0 做精确整数根判定，其余交给变号判据。
//    ② while(abs(l-r) > eps) 用 |l-r| 当终止条件：步长 1 时约 13 轮，
//       精度只有 1e-4，对 2 位小数够用但偏紧；改成固定二分 100 次更稳。
//
//  ── 顺带说明：abs(l - r) 是【正确】的 ──
//     实测 abs(0.4) = 0.4，返回类型 double。
//     C++ 里 <cmath> 提供了 std::abs(double) 重载，这里没走整数版，
//     不是 bug（我特意核实过，没冤枉它）。
// ============================================================
#include <bits/stdc++.h>
using namespace std;

double a, b, c, d;

double f(double x) { return a * x * x * x + b * x * x + c * x + d; }

int main() {
    scanf("%lf%lf%lf%lf", &a, &b, &c, &d);

    double last = -1e18;                       // 去重：相邻两个输出至少差 0.5
    auto emit = [&](double x) {
        if (x - last >= 0.5) { printf("%.2f ", x); last = x; }
    };

    for (int i = -100; i < 100; ++i) {
        double l = i, r = i + 1;
        double fl = f(l), fr = f(r);

        if (fl == 0.0) {                       // ① 端点恰好是根（整数根）
            emit(l);
            continue;
        }
        if (fl * fr < 0) {                     // ② 区间内变号 → 有根
            for (int k = 0; k < 100; ++k) {    // 固定 100 次二分，精度远超 2 位小数
                double mid = (l + r) / 2;
                if (f(mid) * fr > 0) r = mid;
                else                 l = mid;
            }
            emit((l + r) / 2);                 // ★ 原码缺的就是这一句
        }
    }
    if (f(100.0) == 0.0) emit(100.0);          // ③ 单独补右端点 x = 100

    printf("\n");
    return 0;
}
