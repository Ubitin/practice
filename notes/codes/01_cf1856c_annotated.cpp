#include<bits/stdc++.h>
using namespace std;
using ll = long long;

const ll maxn = 1005;          // ⚠️ 数组开够：题面 n ≤ 1000，多留 5 格余量（别按"数量级"开）
ll n, k;
ll a[maxn];                    // 1-based：a[1..n]

// ---------------------------------------------------------------------------
// 判定函数 p(x)：能否用 ≤ k 次操作，把某个位置的值抬到 x
// ---------------------------------------------------------------------------
// ⚠️ 先记住它的"职责边界"（本题最容易混的一点）：
//     p(x) 只回答「靠操作能不能到 x」；
//     「一次都不操作就已经 ≥ x」这条路【不由 p 负责】，而是由二分下界 l = max(a) 负责。
//     因为 p 枚举的"峰位"只到 n-1（可操作的位置），它永远看不到"a[n] 本来就够大"这件事。
// ---------------------------------------------------------------------------
bool p(ll x) {
    for (ll i = 1; i <= n - 1; i++) {   // ⚠️① 枚举"峰"的位置，上界是 n-1 而不是 n：
        //                                    a[n] 没有右侧支撑、永远抬不动，
        //                                    不可能成为"靠操作抬高"的目标（它的值由下界 max(a) 覆盖）
        //                                ⚠️ 但 n-1 必须枚举！位置 n-1 能抬到 a[n]+1
        //                                    （漏掉它：实测随机 2 万组里 11.2% 答案偏小）
        ll rem = k;                     // 剩余操作次数（预算）
        ll need = x;                    // 位置 j 需要的值：i 要 x，i+1 要 x-1，i+2 要 x-2 ……
        ll j = i;                       // ⚠️② 内层从 j = i 开始（此时 need 正好是 x，对应位置 i 的需求）
        for (; j <= n - 1; ++j) {       // ⚠️③ 内层同样只扫到 n-1（n 加不了），最后再单独判 a[n]
            if (a[j] >= need) break;    // ⚠️④ 这一级本来就够高 ⇒ 需求链在这里就撑住了（成功收尾）
            rem -= (need - a[j]);       //      缺多少就补多少
            if (rem < 0) break;         // ⚠️⑤ 预算不够 ⇒ 这个起点失败（失败收尾）
            need--;                     // ⚠️⑥ 往右一格、需求 -1
            //                              顺序不能反：必须"先付代价、再降需求"
            //                              若把 a[i] 又拿 need=x-1 算一遍（从 j=i 再走一圈），
            //                              就会 a[i] 算两次 + need 多减一次 ⇒ 答案时大时小
        }
        // ⚠️⑦ 收尾判定：三种退出方式必须分清（本题最易错的一行）
        //     · 因 `a[j] >= need` 提前 break  ⇒ 链已满足，判 a[j] >= need  ✓
        //     · 内层跑到 j == n 自然结束     ⇒ 只能用 a[n] >= need 兜底    ✓
        //     · 因 rem < 0 break            ⇒ rem >= 0 为假 ⇒ 正确判失败   ✓
        //   ⚠️ 绝不能写成  rem >= 0 || (...) ：
        //      rem >= 0 只说明"钱没花完"，不代表需求链满足！
        //      （写成 || 会让 `3 50 / 1 1 1` 输出 27，正确是 3）
        if (rem >= 0 && (a[j] >= need || a[n] >= need)) return true;
    }
    return false;
}

// ---------------------------------------------------------------------------
// 二分答案（沿用你平时的模板）
// ---------------------------------------------------------------------------
ll find(ll l, ll r) {
    ll best = l;                    // ★修1+★修2：初值必须是 l（= max(a)），绝不能是 0！
    //                              为什么：p(x) 只管"靠操作能不能到 x"；
    //                              而 max(a)（一次都不操作）一定可行 —— 这条路靠下界兜底。
    //                              写 0 的后果：若 max(a) 恰好落在最后一个位置 a[n]，
    //                              则 p(max(a)) 必为 false（想靠操作到 179 要 176 次 > k=13）
    //                              ⇒ best 从没被赋值 ⇒ 输出 0
    //                              （实测 4 13 / 1 1 3 179：输出 0，正确 179）
    while (l <= r) {
        ll mid = (l + r) >> 1;      // ★修3：mid 在循环体里算（原函数开头那句是死代码）
        if (p(mid)) {               // 可行 ⇒ 记下答案往下界方向收
            best = mid;
            l = mid + 1;
        }
        else r = mid - 1;           // 不可行 ⇒ 往小试
    }
    return best;
}

int main(){
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    ll t; cin >> t;                 // ⚠️⑧ 多组数据：每组的 n、k、a 都要重新读
    while (t--) {
        cin >> n >> k;
        ll l = 0, r;
        for (ll i = 1; i <= n; ++i) {
            cin >> a[i];
            l = max(l, a[i]);       // ⚠️⑨ 下界 = max(a)：表示"一次都不操作"一定可行
            //                          ⚠️ 别写 l = a[0]：1-based 里 a[0] 从没赋值（全局恒 0），等于丢掉下界
        }
        r = l + k;                  // ⚠️⑩ 上界 = max(a) + k：k 次全砸在一个位置上
        //                              ⚠️ 别拍脑袋写 r = 1e8：答案最大可到 1e9 + 1e8 = 1.1e9
        //                                 （实测 a=[200000000,200000000], k=5：写 1e8 输出 0，正确 200000001）
        cout << find(l, r) << "\n"; // ⚠️⑪ 每组都要输出并换行（本地测别忘了先给 t）
    }
    return 0;
}

