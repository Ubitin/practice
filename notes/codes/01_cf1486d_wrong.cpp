// ============================================================
//  01_cf1486d_wrong.cpp —— CF1486D 的【错误解】（用于演示对拍能抓出它）
//
//  这就是"所有数进大根堆、弹 ⌊k/2⌋+1 次"那种做法：
//  算的是整个数组的第 t 大，与"长度 >= k 的连续子段的中位数"完全无关。
//
//  它只在 n == k（唯一合法子段就是整个数组）时才必然正确。
//  实测：官方样例 n=5,k=3,a={1,2,3,4,5} 恰好输出 4 = 正确答案，所以看不出问题。
// ============================================================
#include <bits/stdc++.h>
using namespace std;

int main() {
    int n, k;
    if (!(cin >> n >> k)) return 0;
    priority_queue<int> pq;
    for (int i = 0; i < n; ++i) { int x; cin >> x; pq.push(x); }

    int t = (k + 1) / 2;      // = ⌈k/2⌉
    t = k - t + 1;            // = ⌊k/2⌋ + 1
    int ans = 0;
    while (t--) { ans = pq.top(); pq.pop(); }
    cout << ans << '\n';
    return 0;
}
